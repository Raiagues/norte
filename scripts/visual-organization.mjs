/* global window, document */
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright-core';
import { buildApp } from '../server/app.mjs';

const directory = await mkdtemp(join(tmpdir(), 'norte-organization-browser-'));
const app = await buildApp({ storeFile: join(directory, 'state.json'), logger: false, mailer: { configured: false }, ai: { apiKey: '' } });
const port = 5289, base = `http://127.0.0.1:${port}/norte/`;
process.env.NORTE_ALLOWED_ORIGINS = new URL(base).origin;
let browser, vite, page;
try {
  const registration = await app.inject({ method: 'POST', url: '/api/auth/register', payload: { name: 'Engineering Captain', email: 'captain@example.test', password: 'browser organization test passphrase' } });
  assert.equal(registration.statusCode, 201, registration.body);
  const cookie = registration.headers['set-cookie'].split(';')[0];
  await app.listen({ host: "127.0.0.1", port: 0 });
  const apiPort = app.server.address().port;
  vite = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], { env: { ...process.env, VITE_DEMO_MODE: 'false', VITE_API_PROXY_TARGET: `http://127.0.0.1:${apiPort}` }, stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Vite startup timeout')), 15000); vite.stdout.on('data', chunk => { if (String(chunk).includes('Local:')) { clearTimeout(timer); resolve(); } }); vite.once('exit', code => { clearTimeout(timer); reject(new Error(`Vite exited ${code}`)); }); });
  browser = await chromium.launch({ executablePath: process.env.NORTE_CHROME || '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: cookie.split('=')[0], value: cookie.slice(cookie.indexOf('=') + 1), url: new URL(base).origin }]);
  const errors = [];
  page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.evaluate(() => { window.localStorage.setItem('norte-language', 'pt'); });
  // Language preference defaults to Portuguese; use explicit language control if needed.
  await page.getByRole('button', { name: 'PT', exact: true }).click().catch(() => {});
  await page.getByRole('button', { name: /Equipes Encontre/ }).click();
  await page.getByRole('button', { name: 'Criar equipe', exact: true }).click();
  await page.locator('.teams-dialog input[name=name]').fill('Equipe de Engenharia');
  await page.locator('.teams-dialog button[type=submit]').click();
  await page.locator('.teams-dialog').waitFor({ state: 'hidden' });
  await page.evaluate(() => { window.location.hash = '#/'; });
  await page.getByRole('button', { name: /Novo projeto Escolha/ }).click();
  await page.getByLabel('Nome do projeto', { exact: true }).fill('Projeto Pesquisa Norte');
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.getByLabel('Competição', { exact: true }).selectOption('sae-aerodesign');
  await page.getByLabel('Classe / categoria', { exact: true }).selectOption('micro');
  assert.equal(await page.locator('.sector-row').count(), 7);
  await page.getByRole('button', { name: 'Editar Aerodinâmica', exact: true }).click();
  await page.getByLabel('Nome do setor', { exact: true }).fill('Aerodinâmica e simulação');
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click();
  await page.getByLabel('Competição', { exact: true }).selectOption('obsat');
  await page.getByLabel('Modalidade', { exact: true }).selectOption('theoretical');
  assert.equal(await page.locator('.sector-row').count(), 3);
  await page.getByLabel('Competição', { exact: true }).selectOption('sae-aerodesign');
  await page.getByRole('button', { name: 'Editar Aerodinâmica e simulação', exact: true }).waitFor();
  await page.getByLabel('Classe / categoria', { exact: true }).selectOption('micro');
  await page.screenshot({ path: '/tmp/norte-ui-create-desktop.png' });
  await page.getByRole('button', { name: 'Sobre os setores', exact: true }).focus();
  await page.getByRole('tooltip').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('tooltip').count(), 0);
  await page.getByRole('button', { name: 'Organograma', exact: true }).click();
  await page.screenshot({ path: '/tmp/norte-ui-create-chart.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/norte-ui-create-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.getByRole('button', { name: 'Lista', exact: true }).click();
  await page.getByLabel('Equipe', { exact: true }).selectOption({ label: 'Equipe de Engenharia' });
  await page.getByLabel('Nome do projeto', { exact: true }).fill('Aero Micro');
  await page.getByRole('button', { name: 'Criar projeto', exact: true }).click();
  await page.getByRole('heading', { name: 'MEMÓRIA DO PROJETO', exact: true }).waitFor();
  const competition = Object.values(app.missionStore.read().workspace.projects).find(p => p.document.name === 'Aero Micro').document;
  assert.equal(competition.context.programId, 'sae-aerodesign');
  assert.equal(competition.context.categoryId, 'micro');
  assert.ok(competition.context.sectors.some(s => s.name === 'Aerodinâmica e simulação'));
  assert.equal(competition.setup.statement, '');
  for (const route of ['#/', '#/teams', '#/invitations', '#/study-setup', '#/project-team', '#/requirements', '#/software', '#/verification', '#/new-project']) {
    await page.evaluate(hash => { window.location.hash = hash; }, route);
    await page.locator('.app-header .account-badge-trigger').waitFor();
    assert.equal(await page.locator('.account-badge-trigger').count(), 1, route);
    assert.equal(await page.locator('.mission-sidebar').count(), 1, route);
  }
  await page.getByLabel('Nome do projeto', { exact: true }).fill('Projeto Pesquisa Norte');
  await page.getByLabel('Tipo de projeto', { exact: true }).selectOption('research');
  assert.equal(await page.getByLabel('Objetivo inicial (opcional)').count(), 0);
  await page.getByLabel('Equipe', { exact: true }).selectOption({ label: 'Equipe de Engenharia' });
  await page.getByRole('button', { name: 'Criar projeto', exact: true }).click();
  await page.getByRole('heading', { name: 'MEMÓRIA DO PROJETO', exact: true }).waitFor();
  await page.locator('.pm-loading').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: 'Testar ideias', exact: true }).count(), 0);
  const stored = Object.values(app.missionStore.read().workspace.projects).find(p => p.document.name === 'Projeto Pesquisa Norte');
  assert.ok(stored); const projectId = stored.document.id;
  assert.equal(stored.document.projectType, 'research');
  await page.locator('.memory-folders nav').getByRole('button', { name: 'Pesquisa', exact: true }).click();
  await page.getByRole('button', { name: 'Subpasta', exact: true }).click();
  await page.locator('.folder-editor').getByLabel('Nome', { exact: true }).fill('Referências técnicas');
  await page.locator('.folder-editor button[type=submit]').click();
  await page.locator('.folder-editor').waitFor({ state: 'hidden' });
  await page.locator('.pm-artifact-band header').getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.locator('.pm-dialog-form input[name=label]').fill('Relatório de ensaio');
  await page.getByRole('button', { name: 'Escrever documento', exact: true }).click();
  await page.locator('textarea[name=documentText]').fill('# Ensaio\n\n## Resultados\n\n| Item | Resultado |\n| --- | --- |\n| Sensor | Aprovado |\n\n## Referências\n[Manual](https://example.test/manual)');
  await page.locator('.pm-dialog-form button[type=submit]').click();
  await page.locator('.pm-dialog').waitFor({ state: 'hidden' });
  await page.getByRole('link', { name: 'Baixar PDF', exact: true }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Baixar PDF', exact: true }).click();
  const download = await downloadPromise; assert.equal(await download.failure(), null);
  const bytes = app.missionStore.read().artifacts.find(a => a.label === 'Relatório de ensaio');
  assert.ok(bytes.documentText.includes('Sensor')); assert.ok(bytes.folderId);
  await page.reload();
  await page.getByRole('heading', { name: 'MEMÓRIA DO PROJETO', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Abrir: Relatório de ensaio', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Editar', exact: true }).click();
  assert.match(await page.locator('textarea[name=documentText]').inputValue(), /Sensor/);
  await page.locator('.pm-dialog-form select[name=folderId]').selectOption('sector-research-1');
  await page.locator('.pm-dialog-form button[type=submit]').click();
  await page.locator('.pm-dialog').waitFor({ state: 'hidden' });
  assert.equal(app.missionStore.read().artifacts.find(a => a.id === bytes.id).folderId, 'sector-research-1');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/norte-organization-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '/tmp/norte-organization-desktop.png', fullPage: true });
  await page.evaluate(() => { window.location.hash = '#/'; });
  await page.locator('.app-header .account-badge-trigger').click();
  await page.getByRole('button', { name: 'Administrar usuários', exact: true }).click();
  await page.getByRole('heading', { name: 'Usuários da plataforma' }).waitFor();
  await page.getByRole('cell', { name: 'Engineering Captain', exact: true }).waitFor();
  assert.equal(app.missionStore.read().workspace.projects[projectId].document.context.folders.length, 1);
  assert.deepEqual(errors, []);
  console.log('PASS: team + project creation, folders, editable document, PDF download, move, reload, responsive layout and administrative activity.');
} catch (error) { if (page) { await page.screenshot({ path: "/tmp/norte-organization-failed.png", fullPage: true }); console.error(await page.locator("body").innerText()); } throw error;
} finally {
  await browser?.close(); vite?.kill('SIGTERM'); await app.close(); await rm(directory, { recursive: true, force: true });
}
